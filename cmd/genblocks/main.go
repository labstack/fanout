// Command genblocks generates TypeScript type definitions from Go block structs.
// Usage: go run ./cmd/genblocks > client/src/lib/types.ts
package main

import (
	"fmt"
	"os"
	"reflect"
	"strings"

	"github.com/labstack/fanout/internal/ai"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "genblocks: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	var b strings.Builder

	b.WriteString("// Code generated by cmd/genblocks; DO NOT EDIT.\n\n")

	// BlockType union
	b.WriteString("export type BlockType =\n")
	for i, entry := range ai.BlockTypeRegistry {
		if i > 0 {
			b.WriteString("\n")
		}
		sep := ";"
		if i < len(ai.BlockTypeRegistry)-1 {
			sep = ""
		}
		b.WriteString(fmt.Sprintf("  | %q%s", string(entry.Type), sep))
	}
	b.WriteString("\n\n")

	// Block interface
	b.WriteString("export interface Block {\n")
	b.WriteString("  type: BlockType;\n")
	b.WriteString("  data: unknown;\n")
	b.WriteString("}\n\n")

	// Generate data interfaces for each block type
	for _, entry := range ai.BlockTypeRegistry {
		t := reflect.TypeOf(entry.Data)
		if t.Kind() == reflect.Ptr {
			t = t.Elem()
		}
		writeInterface(&b, t)
		b.WriteString("\n")
	}

	// Non-block protocol types (these reference server protocol, not block data)
	b.WriteString(protocolTypes)

	_, err := os.Stdout.WriteString(b.String())
	return err
}

func writeInterface(b *strings.Builder, t reflect.Type) {
	// Collect nested anonymous struct types that need their own interfaces
	nested := collectNestedTypes(t)

	// Write any nested types first
	for _, nt := range nested {
		writeInterface(b, nt)
		b.WriteString("\n")
	}

	b.WriteString(fmt.Sprintf("export interface %s {\n", t.Name()))
	for i := 0; i < t.NumField(); i++ {
		field := t.Field(i)
		if !field.IsExported() {
			continue
		}
		tag := field.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts := parseJSONTag(tag)
		if name == "" {
			name = field.Name
		}
		// *T without omitempty → required but nullable (e.g. parent: string | null)
		// *T with omitempty → optional, not nullable (omitempty skips nil → never null in JSON)
		// plain omitempty → optional (e.g. color?: string)
		fieldType := field.Type
		optMark := ""
		if opts.contains("omitempty") {
			optMark = "?"
			if fieldType.Kind() == reflect.Ptr {
				fieldType = fieldType.Elem() // unwrap: *T with omitempty → T (not nullable)
			}
		}
		tsType := goTypeToTS(fieldType)
		b.WriteString(fmt.Sprintf("  %s%s: %s;\n", name, optMark, tsType))
	}
	b.WriteString("}\n")
}

// collectNestedTypes finds struct types referenced by fields that are named Go types
// (not anonymous) and need their own interface. Returns them in field order.
func collectNestedTypes(t reflect.Type) []reflect.Type {
	seen := map[string]bool{}
	var result []reflect.Type

	for i := 0; i < t.NumField(); i++ {
		field := t.Field(i)
		if !field.IsExported() {
			continue
		}
		ft := unwrapType(field.Type)
		if ft.Kind() == reflect.Struct && ft.Name() != "" && ft.Name() != t.Name() && !isBuiltinType(ft) {
			if !seen[ft.Name()] {
				seen[ft.Name()] = true
				result = append(result, ft)
			}
		}
	}
	return result
}

func unwrapType(t reflect.Type) reflect.Type {
	for t.Kind() == reflect.Ptr || t.Kind() == reflect.Slice {
		t = t.Elem()
	}
	return t
}

func isBuiltinType(t reflect.Type) bool {
	switch t.Kind() {
	case reflect.String, reflect.Bool, reflect.Int, reflect.Int8, reflect.Int16,
		reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint8, reflect.Uint16,
		reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return true
	}
	return false
}

func goTypeToTS(t reflect.Type) string {
	if t.Kind() == reflect.Ptr {
		return goTypeToTS(t.Elem()) + " | null"
	}

	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice:
		elem := t.Elem()
		if elem.Kind() == reflect.Slice {
			// [][]T → T[][]
			return goTypeToTS(elem) + "[]"
		}
		return goTypeToTS(elem) + "[]"
	case reflect.Map:
		if t.Key().Kind() == reflect.String {
			valTS := goTypeToTS(t.Elem())
			return fmt.Sprintf("Record<string, %s>", valTS)
		}
		return "Record<string, unknown>"
	case reflect.Interface:
		return "unknown"
	case reflect.Struct:
		if t.Name() != "" {
			return t.Name()
		}
		return inlineObject(t)
	default:
		return "unknown"
	}
}

func inlineObject(t reflect.Type) string {
	var parts []string
	for i := 0; i < t.NumField(); i++ {
		field := t.Field(i)
		if !field.IsExported() {
			continue
		}
		tag := field.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts := parseJSONTag(tag)
		if name == "" {
			name = field.Name
		}
		optional := opts.contains("omitempty") || field.Type.Kind() == reflect.Ptr
		tsType := goTypeToTS(field.Type)
		optMark := ""
		if optional {
			optMark = "?"
		}
		parts = append(parts, fmt.Sprintf("%s%s: %s", name, optMark, tsType))
	}
	return "{ " + strings.Join(parts, "; ") + " }"
}

type jsonTagOptions string

func (o jsonTagOptions) contains(opt string) bool {
	for o != "" {
		var name string
		i := strings.Index(string(o), ",")
		if i >= 0 {
			name, o = string(o[:i]), jsonTagOptions(o[i+1:])
		} else {
			name, o = string(o), ""
		}
		if name == opt {
			return true
		}
	}
	return false
}

func parseJSONTag(tag string) (string, jsonTagOptions) {
	i := strings.Index(tag, ",")
	if i == -1 {
		return tag, ""
	}
	return tag[:i], jsonTagOptions(tag[i+1:])
}

